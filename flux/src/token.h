#pragma once

#include <string>
#include <utility>
enum class FluxTokenType {
    END_OF_FILE,
    NEWLINE,
    IDENTIFIER,
    NUMBER,
    IMAGINARY,
    DIMENSION,
    STRING,
    OUT,
    PLUS,
    MINUS,
    STAR,
    SLASH,
    FLOOR,
    PERCENT,
    CARET,
    ASSIGN,
    PLUS_EQ,
    MINUS_EQ,
    STAR_EQ,
    SLASH_EQ,
    PERCENT_EQ,
    CARET_EQ,
    EQEQ,
    NOT_EQ,
    LPAREN,
    RPAREN,
    LBRACKET,
    RBRACKET,
    LBRACE,
    RBRACE,
    DOT,
    COMMA,
    COLON,
    GET,
    FOR,
    IF,
    ELSE,
    ELIF,
    WHILE,
    AND,
    OR,
    NOT,
    IN,
    TRUE,
    FALSE,
    NIL,
    LT,
    GT,
    LTE,
    GTE,
    FUNC,
    RETURN,
    INPUT,
    BREAK,
    CONTINUE,
    TRY,
    CATCH,
    PASS,
    CLASS,
    ASSERT,
    FSTRING
};
struct Token {
    FluxTokenType type;
    std::string lexeme;
    int line;
    Token(FluxTokenType t, std::string s, int n)
        : type(t),
          lexeme(std::move(s)),
          line(n) {}
};